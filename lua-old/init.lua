local NIX = require("nix-env")

print("[Hyprland-Lua] Avvio init.lua...")

hl.config({
    autogenerated = false,
    debug = {
        disable_logs = false,
    },
    plugin = NIX.plugins
})

-- Carichiamo i moduli specificati in Nix
for _, mod in ipairs(NIX.configModules) do
    print("[Hyprland-Lua] Caricamento modulo: " .. mod)
    local ok, err = pcall(require, mod)
    if not ok then
        print("[Hyprland-Lua] Errore caricamento " .. mod .. ": " .. err)
        -- Tentativo fallback con prefisso lua (nel caso di strutture diverse)
        ok, err = pcall(require, "lua." .. mod)
        if not ok then
            print("[Hyprland-Lua] Fallito anche fallback lua." .. mod .. ": " .. err)
        end
    end
end

hl.config({
    cursor = {
        no_hardware_cursors = true,
    },
})

hl.env("WLR_NO_HARDWARE_CURSORS", "1")
print("[Hyprland-Lua] init.lua completato.")
